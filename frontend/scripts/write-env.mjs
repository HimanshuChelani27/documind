// Writes public/env.js from DOCUMIND_API_URL so the same build can point at any backend.
import { writeFileSync } from "node:fs";

const apiUrl = (process.env.DOCUMIND_API_URL || "http://localhost:8002").replace(/\/$/, "");
writeFileSync(
  new URL("../public/env.js", import.meta.url),
  `// Generated by scripts/write-env.mjs\nwindow.__DOCUMIND__ = { apiUrl: ${JSON.stringify(apiUrl)} };\n`,
);
console.log(`env.js -> ${apiUrl}`);
